import { camel, orderedParams } from './catalog.js';

const CS_TYPES = { string: 'string', int: 'long', double: 'double', bool: 'bool' };
const CS_KEYWORDS = new Set(['value', 'params', 'string', 'object', 'event', 'base', 'checked', 'default']);

function csName(param) {
  const n = camel(param.name);
  return CS_KEYWORDS.has(n) ? `@${n}` : n;
}

function csType(param) {
  const t = CS_TYPES[param.type];
  if (param.required || t === 'string') return t;
  return `${t}?`;
}

function signature(ev) {
  return orderedParams(ev)
    .map((p) => {
      const decl = `${csType(p)} ${csName(p)}`;
      return p.required ? decl : `${decl} = null`;
    })
    .join(', ');
}

function addLine(p) {
  const v = csName(p);
  const key = JSON.stringify(p.name);
  if (p.required) {
    if (p.type === 'bool') return `p.Add(new Parameter(${key}, ${v} ? 1L : 0L));`;
    if (p.type === 'string') return `p.Add(new Parameter(${key}, Clip(${v})));`;
    return `p.Add(new Parameter(${key}, ${v}));`;
  }
  if (p.type === 'string') return `if (${v} != null) p.Add(new Parameter(${key}, Clip(${v})));`;
  if (p.type === 'bool') return `if (${v}.HasValue) p.Add(new Parameter(${key}, ${v}.Value ? 1L : 0L));`;
  return `if (${v}.HasValue) p.Add(new Parameter(${key}, ${v}.Value));`;
}

function xmlEscape(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

export function generateCSharp(catalog) {
  const methods = catalog.events.map((ev) => {
    const params = orderedParams(ev);
    const docParams = params
      .map((p) => `        /// <param name="${csName(p).replace('@', '')}">${xmlEscape(p.description ?? '')}</param>`)
      .join('\n');
    const body = params.map((p) => `            ${addLine(p)}`).join('\n');
    const header = [`        /// <summary>${xmlEscape(ev.description ?? '')}</summary>`, docParams].filter(Boolean).join('\n');
    const bodyLines = body ? `${body}\n` : '';
    return `${header}
        public static void ${ev.method}(${signature(ev)})
        {
            var p = new List<Parameter>(${params.length + 3});
${bodyLines}            Log(${JSON.stringify(ev.name)}, p);
        }`;
  });

  return `// <auto-generated>
// Generated from catalog/events.yaml (version ${catalog.version}) by tools/codegen.
// Do not edit by hand: change the catalog and run \`npm run codegen\`.
// </auto-generated>
using System.Collections.Generic;
using Firebase.Analytics;

namespace GamesKpi
{
    public static partial class Kpi
    {
        public const int CatalogVersion = ${catalog.version};

${methods.join('\n\n')}
    }
}
`;
}
